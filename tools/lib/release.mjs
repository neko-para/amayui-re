// ─────────────────────────────────────────────────────────── 变更集

/**
 * 算变更集（读 + 重建 + 逐支复核）。
 *
 * @param {ReturnType<typeof loadContext>} ctx
 * @param {{onProgress?: (done:number,total:number)=>void}} [opts]
 * @returns {{bins:Array, agfs:Array, agerc:object|null, problems:string[], warnings:string[], stats:object}}
 */
export function collectChanged(ctx, { onProgress } = {}) {
  const problems = [];
  const warnings = [];

  // ── ① BIN：键集来自 patch.json；字节由「基线 + patch」重建 ──
  const bins = [];
  if (!fs.existsSync(ctx.patchPath)) {
    problems.push(`patch 不在：${ctx.patchPath}（先 pnpm tools patch extract --write）`);
  } else {
    const doc = loadPatch(ctx.patchPath);
    const structural = structuralProblems(doc);
    for (const p of structural) problems.push(`patch 结构不变量：${p}`);
    if (!structural.length) {
      const { mapper, subsSha } = mapperContext(ctx.subsPath);
      if (doc.subsSha !== subsSha) {
        warnings.push(`字典指纹与 patch 记录不一致（patch ${doc.subsSha.slice(0, 12)}… / 当前 ${subsSha.slice(0, 12)}…）—— 重建结果可能对不上 resultSha`);
      }
      let base;
      try {
        base = openRoot(ctx.baseDir);
      } catch (err) {
        problems.push(`基线根打不开：${err.message}`);
        base = null;
      }
      const names = Object.keys(doc.scripts).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
      for (const [i, name] of names.entries()) {
        const entry = doc.scripts[name];
        if (!base) break;
        const hit = base.resolve(name);
        if (!hit) {
          problems.push(`${name}：基线解析不出来（散装没有、ALF 里也没有）`);
          continue;
        }
        let buf;
        try {
          buf = rebuildBin(hit.buf, entry, { lineToBin: mapper.lineToBin });
        } catch (err) {
          problems.push(`${name}：重建失败 —— ${err.message}`);
          continue;
        }
        const sha256 = sha256buf(buf);
        if (sha256 !== entry.resultSha) {
          problems.push(`${name}：重建结果与 resultSha 不符（重建 ${sha256.slice(0, 12)}… / 记录 ${entry.resultSha.slice(0, 12)}…）`);
          continue;
        }
        bins.push({ name, buf, sha256, ops: entry.ops.length, baseFrom: hit.from });
        if (onProgress && (i + 1) % 25 === 0) onProgress(i + 1, names.length);
      }
    }
  }

  // ── ② AGF：集合来自配方，字节来自 ui-bake 的构建产物（本工具不烧图） ──
  const blocks = ctx.blocks ?? listRecipes();
  const agfs = [];
  for (const block of blocks) {
    const file = path.join(ctx.bakedDir, `${block}.AGF`);
    if (!fs.existsSync(file)) {
      problems.push(`AGF 缺件 ${relToRepo(file)} —— 先跑 \`pnpm tools ui-bake build\`（烧图要 headless Chrome，见 tools/ui-bake.md §5.1）`);
      continue;
    }
    const buf = fs.readFileSync(file);
    agfs.push({ block, name: `${block}.AGF`, buf, sha256: sha256buf(buf), file: relToRepo(file) });
  }

  // ── ③ AGERC.DLL：入库的可信产物 ──
  let agerc = null;
  if (!fs.existsSync(ctx.agerc)) {
    problems.push(`AGERC.DLL 不在：${relToRepo(ctx.agerc)}（清单条目 binary/agerc-dist）`);
  } else {
    const buf = fs.readFileSync(ctx.agerc);
    agerc = { name: 'AGERC.DLL', buf, sha256: sha256buf(buf), file: relToRepo(ctx.agerc) };
  }

  return {
    bins,
    agfs,
    agerc,
    problems,
    warnings,
    stats: { bins: bins.length, ops: bins.reduce((a, b) => a + b.ops, 0), agfs: agfs.length, agerc: agerc ? 1 : 0 },
  };
}

