/**
 * 版本节：取 `release/CHANGELOG.md` 的**第一个** `## v…` 节。
 * 形态只有两种（规格见 `release/README.md` §4）：`## v1.14（开发中）` / `## v1.14（2026-10-03）`。
 * @returns {null | {version:string, mark:string, dev:boolean, date:string|null, zipName:string|null}}
 */
export function changelogVersion(text) {
  const m = /^##[ \t]+(v\d+(?:\.\d+)*)[ \t]*[（(][ \t]*([^）)\r\n]*?)[ \t]*[）)][ \t]*$/m.exec(String(text ?? ''));
  if (!m) return null;
  const [, version, mark] = m;
  const dev = /开发中/.test(mark);
  const date = /^(\d{4})-(\d{2})-(\d{2})$/.exec(mark.trim());
  return {
    version,
    mark: mark.trim(),
    dev,
    date: date ? date[0] : null,
    // 与旧仓 zip 命名一脉相承：发布版 `v1.13-260901.zip`；未发布（开发中）用 `-dev` 且**不编日期**
    zipName: dev ? `${version}-dev.zip` : date ? `${version}-${date[1].slice(2)}${date[2]}${date[3]}.zip` : null,
  };
}

/** 发行字体（`corpus/assets/fonts/Amayui-CN_cnjp*.ttf`） */
export function distributionFonts(ctx) {
  const problems = [];
  if (!fs.existsSync(ctx.fontsDir)) return { fonts: [], problems: [`字体目录不在：${relToRepo(ctx.fontsDir)}`] };
  const names = fs.readdirSync(ctx.fontsDir).filter((n) => FONT_RE.test(n)).sort();
  if (!names.length) problems.push(`字体目录里没有 Amayui-CN_cnjp*.ttf：${relToRepo(ctx.fontsDir)}`);
  const fonts = names.map((n) => {
    const buf = fs.readFileSync(path.join(ctx.fontsDir, n));
    return { name: n, buf, sha256: sha256buf(buf), file: `${relToRepo(ctx.fontsDir)}/${n}` };
  });
  return { fonts, problems };
}

/** 随包文本（`release/CHANGELOG.md` · `release/安装说明.md`；**逐字复制**，不改一个字节） */
export function releaseTexts(ctx, names = RELEASE_TEXTS) {
  const problems = [];
  const texts = [];
  for (const n of names) {
    const f = path.join(ctx.releaseDir, n);
    if (!fs.existsSync(f)) { problems.push(`随包文本不在：${relToRepo(f)}`); continue; }
    const buf = fs.readFileSync(f);
    texts.push({ name: n, buf, sha256: sha256buf(buf), file: relToRepo(f) });
  }
  return { texts, problems };
}

/**
 * 发行包的**条目表**（顺序固定 ⇒ 同输入同字节；旧仓 zip 的目录形状见 `release/README.md` §3）。
 * @returns {{rows:Array, problems:string[], version:object|null, zipName:string|null}}
 */
export function packPlan(ctx, changed, { zipPath = null } = {}) {
  const problems = [];
  const rows = [];

  for (const b of changed.bins) {
    rows.push({ entry: `BIN/${b.name}`, kind: 'bin', source: `patch.json ← 基线 ${b.baseFrom}`, buf: b.buf, sha256: b.sha256 });
  }
  for (const a of changed.agfs) {
    rows.push({ entry: `AGF/${a.name}`, kind: 'agf', source: `ui-bake 配方 ${a.block} · ${a.file}`, buf: a.buf, sha256: a.sha256 });
  }
  if (changed.agerc) {
    rows.push({ entry: changed.agerc.name, kind: 'agerc', source: changed.agerc.file, buf: changed.agerc.buf, sha256: changed.agerc.sha256 });
  }

  const f = distributionFonts(ctx);
  problems.push(...f.problems);
  for (const x of f.fonts) rows.push({ entry: x.name, kind: 'font', source: x.file, buf: x.buf, sha256: x.sha256 });

  const t = releaseTexts(ctx);
  problems.push(...t.problems);
  for (const x of t.texts) rows.push({ entry: x.name, kind: 'text', source: x.file, buf: x.buf, sha256: x.sha256 });

  // 版本节：**包里必须有当前版本节**（旧仓的 CHANGELOG 与包是一起长出来的，脱节就是发错包）
  const cl = t.texts.find((x) => x.name === 'CHANGELOG.md');
  let version = null;
  if (cl) {
    version = changelogVersion(cl.buf.toString('utf8'));
    if (!version) problems.push('release/CHANGELOG.md 里找不到版本节（规格：`## vX.Y（开发中）` 或 `## vX.Y（YYYY-MM-DD）`）');
    else if (!version.zipName) problems.push(`release/CHANGELOG.md 的版本节形态不合规格：\`## ${version.version}（${version.mark}）\`（标注只能是「开发中」或日期）`);
  }

  const dup = rows.map((r) => r.entry).filter((n, i, a) => a.indexOf(n) !== i);
  if (dup.length) problems.push(`条目重名：${[...new Set(dup)].join(', ')}`);

  const name = zipPath ? path.basename(zipPath) : version?.zipName ?? null;
  const zipPathFinal = zipPath ?? (name ? path.join(ctx.zipDir, name) : null);
  return { rows, problems, version, zipName: name, zipPath: zipPathFinal };
}

/**
 * 写 zip + 同名清单，并**读回复验**（逐条目反解比对；不绿删掉 zip、不留残件）。
 * @returns {{ok:boolean, problems:string[], bytes?:number, sha256?:string, manifestPath?:string, zipPath?:string}}
 */
export function writePack(ctx, plan) {
  const { rows, zipPath } = plan;
  if (!zipPath) return { ok: false, problems: ['算不出版本 ⇒ 不知道 zip 叫什么（用 --zip 显式指定，或修 CHANGELOG）'] };
  const manifestPath = ctx.packManifest ?? zipPath.replace(/\.zip$/i, '.manifest.json');

  let zip;
  try {
    zip = buildZip(rows.map((r) => ({ name: r.entry, data: r.buf })));
  } catch (err) {
    return { ok: false, problems: [`打包失败：${err.message}`] };
  }

  fs.mkdirSync(path.dirname(zipPath), { recursive: true });
  // ★ 先写临时件、读回复验过了再改名 —— 失败时不毁掉上一版 zip
  const tmp = `${zipPath}.tmp`;
  fs.writeFileSync(tmp, zip);

  // ★ 写后回读复验：条目集合 + 每条**逐字节**
  const problems = [];
  try {
    const back = readZip(fs.readFileSync(tmp));
    const want = new Set(rows.map((r) => r.entry));
    for (const n of want) if (!back.has(n)) problems.push(`回读缺条目：${n}`);
    for (const n of back.keys()) if (!want.has(n)) problems.push(`回读多出条目：${n}`);
    for (const r of rows) {
      const got = back.get(r.entry);
      if (got && !got.equals(r.buf)) problems.push(`回读不一致：${r.entry}`);
    }
  } catch (err) {
    problems.push(`回读失败：${err.message}`);
  }
  if (problems.length) {
    fs.rmSync(tmp, { force: true });
    return { ok: false, problems };
  }
  fs.renameSync(tmp, zipPath);

  const sha256 = sha256buf(zip);
  const manifest = {
    schemaVersion: 1,
    _doc: '本文件是**生成物**（发行包的自检记录）：字段语义 / 怎么查怎么改见 `pnpm tools release describe`。由 pnpm tools release pack 写入，不要手改。',
    version: plan.version?.version ?? null,
    mark: plan.version?.mark ?? null,
    zip: path.basename(zipPath),
    zipSha256: sha256,
    entries: rows.map((r) => ({ entry: r.entry, kind: r.kind, source: r.source, bytes: r.buf.length, sha256: r.sha256 })),
  };
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 1)}\n`);
  return { ok: true, problems: [], bytes: zip.length, sha256, manifestPath, zipPath, entries: rows.length };
}

