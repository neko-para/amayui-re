/**
 * 测试安装树 = **基础树（游戏安装根）** + **变更集覆盖**。
 *
 * 它等价于《安装说明》第 1–5 步：复制一份游戏 → 移出 `AGE-EXTEND.TTF` → 覆盖 BIN / AGF / AGERC.DLL。
 * 差别只有一处：`*.ALF`（7.4 GiB 的只读大件）走**硬链接**而不是真拷贝。
 *
 * ★ 硬链接的代价必须显式说：链接与游戏安装根**是同一个 inode** ⇒ **任何往测试树里写的动作都会改到本体**。
 *   所以本工具只把"我们自己的产物"（BIN / AGF / AGERC）写成真文件，基础树里的件**只读**。
 * @returns {{base:Array, overlays:Array, excluded:Array, dirs:string[], problems:string[]}}
 */
export function installPlan(ctx, changed) {
  const problems = [];
  const base = [];
  const excluded = [];
  const dirs = [];

  if (!fs.existsSync(ctx.baseDir)) {
    problems.push(`基线根不在：${ctx.baseDir}（清单 roots.gameInstall）`);
  } else {
    const entries = fs.readdirSync(ctx.baseDir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const e of entries) {
      if (!e.isFile()) { dirs.push(e.name); continue; }
      const why = excludeReason(e.name, ctx.exclude);
      if (why) { excluded.push({ name: e.name, why }); continue; }
      const src = path.join(ctx.baseDir, e.name);
      const hardlink = path.extname(e.name).toUpperCase() === '.ALF' && ctx.alfMode !== 'copy';
      base.push({
        path: e.name,
        action: hardlink ? 'hardlink' : 'copy',
        source: relToRepo(src),
        bytes: fs.statSync(src).size,
      });
    }
  }

  // 覆盖件：先按**基础树里已有的大小写**落（大小写不敏感的文件系统上就是同一个文件；
  // 大小写敏感的机器上也不会凭空多出一份 `so025.AGF` + `SO025.AGF`）
  const baseLower = new Map(base.map((r) => [r.path.toLowerCase(), r.path]));
  const overlays = [];
  const push = (o) => {
    const hit = baseLower.get(o.path.toLowerCase());
    overlays.push(hit ? { ...o, path: hit, replaces: hit } : o);
  };
  for (const b of changed.bins) push({ path: b.name, kind: 'bin', buf: b.buf, sha256: b.sha256, source: 'patch.json' });
  for (const a of changed.agfs) push({ path: a.name, kind: 'agf', buf: a.buf, sha256: a.sha256, source: a.file });
  if (changed.agerc) push({ path: changed.agerc.name, kind: 'agerc', buf: changed.agerc.buf, sha256: changed.agerc.sha256, source: changed.agerc.file });

  // 可选的 LE 启动器（旧仓 install/ 里那份的等价物；**不是**游戏件，是"怎么起这棵树"的说明）
  if (ctx.leCmd) {
    const l = leLauncher(ctx);
    problems.push(...l.problems);
    if (l.buf) push({ path: LE_LAUNCHER_NAME, kind: 'launcher', buf: l.buf, sha256: sha256buf(l.buf), source: '本工具生成（--le-cmd / --le-profile）' });
  }

  const dup = overlays.map((o) => o.path.toLowerCase()).filter((n, i, a) => a.indexOf(n) !== i);
  if (dup.length) problems.push(`覆盖件重名：${[...new Set(dup)].join(', ')}`);

  return { base, overlays, excluded, dirs, problems };
}

/** 读回本工具上次写的安装树清单（决定"能不能就地同步"与"哪些覆盖件已经过时"） */
export function readInstallManifest(p) {
  if (!fs.existsSync(p)) return null;
  try {
    const m = JSON.parse(fs.readFileSync(p, 'utf8'));
    if (m?.schemaVersion !== 1 || !Array.isArray(m.overlays)) return null;
    return m;
  } catch {
    return null;
  }
}

/** 同一个 inode？`ino` 拿不到时退化成"大小 + mtime 相同"（不假装知道） */
function sameFile(a, b) {
  const A = fs.statSync(a);
  const B = fs.statSync(b);
  if (A.ino && B.ino) return A.ino === B.ino && A.dev === B.dev;
  return A.size === B.size && Math.floor(A.mtimeMs) === Math.floor(B.mtimeMs);
}

/**
 * 这个复制件还是不是源的那一份？—— **大小 + mtime（±2 ms）**。
 * ★ 为什么要容差：`utimesSync` 只接受毫秒精度的 `Date`，而 `statSync().mtimeMs` 带亚毫秒小数
 *   ⇒ 写回去会比源**大不到 1 ms**（实测 1791108145543 vs 1791108145542.6853）。
 *   拿 `===` 判就会每次重跑都重拷一遍（幂等性当场失效）。
 */
function sameCopy(src, dst) {
  const A = fs.statSync(src);
  const B = fs.statSync(dst);
  return A.size === B.size && Math.abs(B.mtimeMs - A.mtimeMs) < 2;
}

/**
 * 落盘：基础树（ALF 硬链接 / 其余复制）→ 覆盖件（真文件）→ 清掉上一次留下的过时覆盖件。
 *
 * 顺序是有讲究的：**先清过时覆盖件、再同步基础树、最后写覆盖件** ——
 * 这样"上一轮是覆盖件、这一轮变回基础件"的那个名字会被基础树重新铺回原版（而不是留着旧译文）。
 * @returns {{ok:boolean, problems:string[], stats?:object}}
 */
function installTree(ctx, plan, { force = false, log = () => {}, relabel = false } = {}, state = {}) {
  const outDir = ctx.outDir;
  const manifestPath = ctx.installManifest;
  const problems = [...plan.problems];

  if (fs.existsSync(outDir) && !fs.statSync(outDir).isDirectory()) {
    problems.push(`落点已被一个文件占着：${outDir}`);
  }
  if (problems.length) return { ok: false, problems };

  const existed = fs.existsSync(outDir) && fs.readdirSync(outDir).length > 0;
  const prev = existed ? readInstallManifest(manifestPath) : null;
  if (existed && !prev && !force) {
    return {
      ok: false,
      problems: [
        `${outDir} 已存在且不是本工具建的（没有 ${relToRepo(manifestPath)}）`,
        '要么换 --out，要么先清空它，要么加 --force 表示"我知道里面是什么"',
      ],
    };
  }

  fs.mkdirSync(outDir, { recursive: true });
  const stats = { hardlink: 0, copy: 0, skip: 0, write: 0, prune: 0, bytes: 0, verified: 0 };
  const written = [];
  /** 失败处置：**这一轮新建的树整棵撤掉**（否则会留下一棵"有一半基础件、又没有清单"的假树） */
  const fail = (problems) => {
    if (!existed) fs.rmSync(outDir, { recursive: true, force: true });
    else problems.push('⚠ 这次失败落在同步途中：目标目录可能处于混合状态 —— 重跑一次即可收敛（基础树同步是幂等的）');
    return { ok: false, problems };
  };
  state.fail = fail; // 外层薄壳（writeInstall）兜住意外抛出时也走同一条回滚

  // ★ **先探一次**硬链接能力（一次 link + unlink，只动元数据）：拿不到就直接报，别写了一半才发现
  const firstLink = plan.base.find((r) => r.action === 'hardlink');
  if (firstLink) {
    const probe = path.join(outDir, '.release-link-probe');
    fs.rmSync(probe, { force: true }); // 上次跑到一半留下的探针（只可能在 outDir 里，因为它必须同卷）
    try {
      fs.linkSync(path.join(ctx.baseDir, firstLink.path), probe);
      fs.rmSync(probe, { force: true });
    } catch (err) {
      fs.rmSync(probe, { force: true });
      return fail([
        `硬链接不可用（试的是 ${firstLink.path}）：${err.code ?? ''} ${err.message}`,
        '两种成因，各自有各自的处置：',
        `  ① **不同卷**（EXDEV）：硬链接要求基线根与落点在同一个盘符（现在是 ${path.parse(ctx.baseDir).root} → ${path.parse(outDir).root}）`
          + ' ⇒ 把测试树放到游戏所在的盘上，或加 `--alf copy`（真拷贝，多占 ~7.4 GB）',
        '  ② **权限不足**（EPERM/EACCES）：建硬链接会**改到源文件的链接数**，所以它不是纯读操作 ——'
          + '受限沙箱 / 只读 ACL 下会被拒 ⇒ 用 `--alf copy`，或让这一步在能写游戏目录的环境里跑',
        `  ③ **落点落在沙箱可写范围之外**：这棵子树若被改成 Medium 完整性（\`--relabel-medium\`），`
          + '受限子进程就只能写带 Low 标签的根 ⇒ 见 tools/release.md §3.1（提权跑一次，或把树建到工作区之外）',
      ]);
    }
  }

  // ① 清掉上一轮的过时覆盖件（**只清我们写过的**；名字若回到基础树里则由 ② 重新铺）
  const nowOverlay = new Set(plan.overlays.map((o) => o.path.toLowerCase()));
  const basePaths = new Set(plan.base.map((r) => r.path.toLowerCase()));
  for (const o of prev?.overlays ?? []) {
    if (nowOverlay.has(String(o.path).toLowerCase())) continue;
    const abs = path.join(outDir, o.path);
    if (!fs.existsSync(abs)) continue;
    if (basePaths.has(String(o.path).toLowerCase())) continue; // ② 会重铺，别在这里删
    fs.rmSync(abs, { force: true });
    stats.prune += 1;
    log(`- 过时覆盖件已清：${o.path}`);
  }

  // ② 基础树（★ 已经是覆盖件的名字**不铺基础件** —— ③ 会写它；否则每次重跑都会"复制→再覆盖"一遍）
  for (const r of plan.base) {
    if (nowOverlay.has(r.path.toLowerCase()) && r.action !== 'hardlink') { stats.skip += 1; continue; }
    const src = path.join(ctx.baseDir, r.path);
    const dst = path.join(outDir, r.path);
    if (r.action === 'hardlink') {
      if (fs.existsSync(dst) && sameFile(src, dst)) { stats.skip += 1; continue; }
      // ★ 先删链接再建：**绝不能**写穿到本体（同 inode）
      if (fs.existsSync(dst)) fs.rmSync(dst, { force: true });
      try {
        fs.linkSync(src, dst);
      } catch (err) {
        return fail([
          `硬链接失败：${r.path} —— ${err.code ?? ''} ${err.message}`,
          '（预探过了却在中途失败 ⇒ 多半是并发改动了游戏目录；重跑一次）',
        ]);
      }
      stats.hardlink += 1;
    } else {
      const ss = fs.statSync(src);
      if (fs.existsSync(dst) && sameCopy(src, dst)) { stats.skip += 1; continue; }
      fs.copyFileSync(src, dst);
      fs.utimesSync(dst, ss.atime, ss.mtime); // 保住来源时间戳（也让上面的"跳过"判据成立）
      stats.copy += 1;
      stats.bytes += ss.size;
    }
  }

  // ③ 覆盖件
  for (const o of plan.overlays) {
    const dst = path.join(outDir, o.path);
    const old = fs.existsSync(dst) ? sha256buf(fs.readFileSync(dst)) : null;
    if (old === o.sha256) { stats.skip += 1; continue; }
    fs.writeFileSync(dst, o.buf);
    stats.write += 1;
    stats.bytes += o.buf.length;
    written.push(o.path);
    log(`+ ${o.path}`);
  }

  // ④ 写后回读复验（覆盖件逐字节 + ALF 逐个 ino）
  const verifyProblems = [];
  for (const o of plan.overlays) {
    const dst = path.join(outDir, o.path);
    if (!fs.existsSync(dst)) { verifyProblems.push(`回读缺覆盖件：${o.path}`); continue; }
    if (sha256buf(fs.readFileSync(dst)) !== o.sha256) verifyProblems.push(`回读不一致：${o.path}`);
    else stats.verified += 1;
  }
  for (const r of plan.base) {
    if (r.action !== 'hardlink') continue;
    const dst = path.join(outDir, r.path);
    if (!fs.existsSync(dst) || !sameFile(path.join(ctx.baseDir, r.path), dst)) verifyProblems.push(`回读：${r.path} 不是硬链接（或链错了对象）`);
  }
  if (verifyProblems.length) {
    for (const p of written) fs.rmSync(path.join(outDir, p), { force: true }); // 回滚本次覆盖件
    return fail(verifyProblems);
  }

  // ⑤ 清单（**生成物**：记录这一棵树是怎么来的；也是下一次同步的"上一轮"）
  const manifest = {
    schemaVersion: 1,
    _doc: '本文件是**生成物**（测试安装树的自检记录）：字段语义 / 怎么查怎么改见 `pnpm tools release describe`。由 pnpm tools release install 写入，不要手改。',
    baseDir: ctx.baseDir,
    outDir,
    rows: [
      ...plan.base.map((r) => ({ path: r.path, action: r.action, kind: 'base', bytes: r.bytes })),
      ...plan.overlays.map((o) => ({ path: o.path, action: 'write', kind: o.kind, bytes: o.buf.length, sha256: o.sha256, source: o.source })),
    ],
    overlays: plan.overlays.map((o) => ({ path: o.path, kind: o.kind, sha256: o.sha256, source: o.source })),
    excluded: plan.excluded,
  };
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 1)}\n`);

  // ⑤ 环境口径：Low 完整性标签（详见 lowIntegrityLabel 的注释 —— 它会让 LE 起不来）
  const warnings = [];
  let relabeled = null;
  const probe = path.join(outDir, 'AGE.EXE');
  const label = lowIntegrityLabel(fs.existsSync(probe) ? probe : outDir);
  if (label.error) warnings.push(`完整性标签没查出来（icacls 跑不起来：${label.error}）—— 若这棵树要给 Locale Emulator 用，留意 lowLabelAdvice`);
  else if (label.low) {
    if (relabel) {
      const r = relabelMedium(outDir);
      relabeled = r.ok ? 'ok' : r.reason;
      if (!r.ok) warnings.push(...lowLabelAdvice(outDir), `  ⇒ --relabel-medium 失败：${r.reason}`);
    } else {
      warnings.push(...lowLabelAdvice(outDir));
    }
  }

  return { ok: true, problems: [], stats, manifestPath, outDir, warnings, relabeled };
}

/**
 * 落盘（**唯一写入口**）。
 * ★ 为什么要一层薄壳：落盘的每一步都可能被**环境**挡下（不同卷 / 权限 / 目标子树被改成 Medium 完整性后
 *   落在受限沙箱的可写范围之外，见 `tools/release.md` §3.1）—— 整段兜住，出错走同一个 `fail()`
 *   （新建的树整棵撤掉、就地同步的如实报"可能混合"），**不留半棵树**。
 */
export function writeInstall(ctx, plan, opts = {}) {
  const state = {};
  try {
    return installTree(ctx, plan, opts, state);
  } catch (err) {
    const extra = [];
    if (err.code === 'EACCES' || err.code === 'EPERM') {
      extra.push('（权限类错误：目标子树若已改成 **Medium 完整性**，它就落在受限沙箱的**可写范围之外**了 ——');
      extra.push('  处置见 tools/release.md §3.1：提权跑一次，或把树建到工作区之外）');
    }
    const problems = [`落盘过程中出错：${err.code ?? ''} ${err.message}`, ...extra];
    return typeof state.fail === 'function' ? state.fail(problems) : { ok: false, problems };
  }
}

