/**
 * tools/lib/release.mjs — **发行打包的领域模型**（"变更集 → 两种形状"的那半边）
 *
 * 一句话：把**当前所有变更过的资源**算出来，然后铺成两种形状 ——
 *   ① **测试安装树**（旧仓 `install/` 的等价物：基础树 + 覆盖件；ALF 走硬链接）
 *   ② **发行包**（旧仓 `patch/` 的等价物：一个 zip，只有玩家要的那几件）
 *
 * ## 为什么两条命令共用一个模型
 * 两者**输入完全相同**（变更集），差的只是"铺成什么形状"。变更集的算法只写一遍，
 * 于是"装进测试树的"与"发给玩家的"**必然是同一批字节** —— 这正是旧仓最容易漂的地方
 * （`patch/patch.config.json` 是一份手维护清单，实测与 `patch.json` 的键差 2 支：`$1$SCINIT.BIN` /
 *  `$1$SCJUMP.BIN` 没进包、`$3$DPINIT.BIN` / `$5$AMINIT2.BIN` 多出来）。
 *
 * ## 变更集 = 三处真源（**没有第四处**）
 * | 件 | 真源 | 谁是"变了"的判据 |
 * |---|---|---|
 * | `*.BIN`（453 支） | `data/translations/patch.json` 的**键** | 基线 + patch 重建出来的字节（`resultSha` 逐支复核） |
 * | `*.AGF`（10 张） | `tools/ui-bake/recipes/*.json` 的**配方集合** | `pnpm tools ui-bake build` 的产物 `dist/ui-bake/<块>.AGF` |
 * | `AGERC.DLL`（1 个） | `corpus/assets/agerc/AGERC.DLL`（可信产物，见 `release/README.md` §5.2） | 入库件本身就是成品 |
 *
 * ★ **不存同步清单**：旧仓 `patch.config.json` 那种"再把上面三处的结论抄一遍"的文件，
 *   是第二真源 —— 抄的那一刻起就注定与真源漂。清单在这里是**算出来的**。
 * ★ **AGF 不由本工具烧**：烧 AGF 要 headless Chrome（沙箱里要提权），那是 `tools/ui-bake.mjs` 的活；
 *   本工具**只消费它的产物**，缺产物就报"先跑哪条命令"，不自己凑一张图。
 *
 * ## 两条写路径的共同纪律
 * 写前：把所有问题一次算完（缺件 / 键集不符 / 版本节不合规格 ⇒ **一个字都不写**）；
 * 写后：**回读复验**（zip 逐条目反解比对；安装树的覆盖件逐个 sha256、ALF 逐个 ino 比对），
 *       不绿就回滚（zip 删掉、本次写入的覆盖件删掉）。
 */
