export function describeText(d = describe()) {
  const L = [];
  L.push('# 发行打包 —— 自描述（由控制脚本给出，文档不复述 schema）');
  L.push('');
  L.push(`用途：${d.purpose}`);
  L.push('');
  L.push('## 变更集从哪来（★ 没有第四处同步清单）');
  for (const c of d.changedSet) L.push(`* \`${c.kind}\` ← ${c.from}\n  ${c.note}`);
  L.push('');
  L.push('## 包里有什么（顺序固定 ⇒ 同输入同字节）');
  for (const s of d.packShape) L.push(`* ${s}`);
  L.push('');
  L.push('## 测试安装树长什么样');
  for (const s of d.installShape) L.push(`* ${s}`);
  L.push('');
  L.push('## 不变量（含"谁在守它"）');
  for (const inv of d.invariants) L.push(`${inv.id}. ${inv.text}　—　${inv.enforcedBy.join(' + ')}`);
  L.push('');
  L.push('## 操作');
  for (const o of d.operations) L.push(`* \`${o.name}\`${o.mutates ? '（会写）' : ''} —— ${o.summary}`);
  L.push('');
  L.push(`写入口：${d.writePath}`);
  L.push('');
  L.push('## 怎么查 / 怎么改');
  for (const h of d.howTo) L.push(`  ${h}`);
  return `${L.join('\n')}\n`;
}
