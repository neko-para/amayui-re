namespace {

namespace fs = std::filesystem;

// 一轮往返的帧表（与 .tmp 里实测脚本同一组帧：130 进 / 180 右键 / 250 再进 …）。
constexpr int kFirstEnterFrame = 130;
constexpr int kEnterToBackFrames = 50;
constexpr int kBackToEnterFrames = 70;
// ★ 轮数（参数化：崩溃发生在"第 2 次进 OPTION"，2 轮就能判；不随轮数增长仍可比较 1→2）。
constexpr int kCycles = 2;

// 轮数 → 脚本正文。动作帧号必须与上面的帧表一致（⛔ 不要在两边各写一套数字）。
std::string makeScript(int cycles) {
    std::string s;
    s += "# generated by tests/option_roundtrip.cpp —— TITLE ⇄ OPTION × " + std::to_string(cycles) + "\n";
    int frame = kFirstEnterFrame;
    s += "at frame " + std::to_string(frame) + "\n";
    for (int i = 0; i < cycles; ++i) {
        s += "click 812 622\n";  // 进 OPTION
        frame += kEnterToBackFrames;
        s += "wait " + std::to_string(kEnterToBackFrames) + " frames\n";
        s += "click 640 360 right\n";  // 右键退回 TITLE
        frame += kBackToEnterFrames;
        s += "wait " + std::to_string(kBackToEnterFrames) + " frames\n";
    }
    s += "quit\n";
    return s;
}

std::string readAllBytes(const fs::path& p) {
    std::ifstream in(p, std::ios::binary);
    if (!in) return {};
    return std::string(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
}

std::wstring quoteArg(const std::wstring& s) { return L"\"" + s + L"\""; }

// 解析 `arena     : surfaces N in_use U peak P largest-free F`（最后一行生效）。
struct ArenaStats {
    unsigned long long surfaces = 0;
    unsigned long long in_use = 0;
    unsigned long long peak = 0;
    unsigned long long largest_free = 0;
    bool found = false;
};

ArenaStats parseArena(const std::string& log) {
    ArenaStats st;
    const std::string key = "arena     : surfaces ";
    std::size_t at = 0;
    while ((at = log.find(key, at)) != std::string::npos) {
        unsigned long long surfaces = 0, in_use = 0, peak = 0, largest = 0;
        const char* p = log.c_str() + at;
        if (std::sscanf(p,
                        "arena     : surfaces %llu in_use %llu peak %llu largest-free %llu", &surfaces,
                        &in_use, &peak, &largest) == 4) {
            st.surfaces = surfaces;
            st.in_use = in_use;
            st.peak = peak;
            st.largest_free = largest;
            st.found = true;
        }
        at += key.size();
    }
    return st;
}

long countAppliedClicks(const std::string& log) {
    long n = 0;
    std::size_t at = 0;
    const std::string key = "[input-script] frame=";
    while ((at = log.find(key, at)) != std::string::npos) {
        const std::size_t eol = log.find('\n', at);
        const std::string line = log.substr(at, eol == std::string::npos ? std::string::npos : eol - at);
        if (line.find(" click ") != std::string::npos) ++n;
        at += key.size();
    }
    return n;
}

bool contains(const std::string& hay, const char* needle) {
    return hay.find(needle) != std::string::npos;
}

#if defined(_WIN32)
struct ChildResult {
    DWORD exit_code = 0xFFFFFFFFu;
    bool started = false;
};

// stdout 与 stderr 都重定向到**同一个**日志文件；不捕获管道。
ChildResult runChild(const fs::path& exe, const std::wstring& args, const fs::path& log_path) {
    ChildResult r;
    SECURITY_ATTRIBUTES sa{};
    sa.nLength = sizeof(sa);
    sa.bInheritHandle = TRUE;
    const HANDLE h = ::CreateFileW(log_path.c_str(), GENERIC_WRITE, FILE_SHARE_READ, &sa, CREATE_ALWAYS,
                                   FILE_ATTRIBUTE_NORMAL, nullptr);
    if (h == INVALID_HANDLE_VALUE) return r;
    STARTUPINFOW si{};
    si.cb = sizeof(si);
    si.dwFlags = STARTF_USESTDHANDLES;
    si.hStdOutput = h;
    si.hStdError = h;
    PROCESS_INFORMATION pi{};
    std::wstring cmd = quoteArg(exe.wstring()) + L" " + args;
    const BOOL ok = ::CreateProcessW(exe.c_str(), cmd.data(), nullptr, nullptr, TRUE, CREATE_NO_WINDOW, nullptr,
                                     nullptr, &si, &pi);
    ::CloseHandle(h);
    if (!ok) return r;
    r.started = true;
    // 4 分钟上限（正常一轮 15~30 s；卡住时必须红，而不是挂死流水线）。
    const DWORD waited = ::WaitForSingleObject(pi.hProcess, 240000u);
    if (waited != WAIT_OBJECT_0) {
        ::TerminateProcess(pi.hProcess, 991u);
        ::WaitForSingleObject(pi.hProcess, 10000u);
    }
    ::GetExitCodeProcess(pi.hProcess, &r.exit_code);
    ::CloseHandle(pi.hThread);
    ::CloseHandle(pi.hProcess);
    return r;
}
#endif

// 环境不可用（不是判据红）：GPU / 窗口 / 执行源。⚠ 不要匹配 `game-dir` —— 那行每个
// 正常启动都会打印（会把任何非 0 退出都误判成环境问题）。
bool environmentUnavailable(const std::string& log) {
    return contains(log, "要求 GPU 光栅化") || contains(log, "窗口打开失败") ||
           contains(log, "找不到执行源") || contains(log, "拒绝启动");
}

}  // namespace

int main(int argc, char** argv) {
    using namespace lift_test;
    // ★ 用例名**保留** `/3cycles`：需求单 `01M6WTRF0X6362NK8BNK8DHHWJ` 与
    //   `01M6X4M4NSRSNX2B0G0DQSFAD1` 的 `repro` 锚点指向它；改名会让
    //   `pnpm tools requirements validate` #3 红，而那两张单不在本次写权限内。
    //   实际轮数 = `kCycles`（= 2）；判据与变异都不依赖这个字符串。
    g_current_case = "option-roundtrip/3cycles";
#if !defined(_WIN32)
    (void)argc;
    (void)argv;
    LIFT_SKIP("本守卫用 CreateProcessW 起子进程（Windows 专有）；非 Windows 侧不跑");
#else
    const std::vector<std::string> args = lift::argvUtf8(argc, argv);
    if (args.size() < 4) {
        std::fprintf(stderr, "用法：lift-option-roundtrip <emulator-lift.exe> <game-dir> <work-dir>\n");
        return 2;
    }
    const fs::path exe = fs::path(lift::utf8ToWide(args[1]));
    const fs::path game_dir = fs::path(lift::utf8ToWide(args[2]));
    const fs::path work_dir = fs::path(lift::utf8ToWide(args[3]));
    std::error_code ec;
    fs::create_directories(work_dir, ec);
    const fs::path appdata = work_dir / "appdata";
    fs::create_directories(appdata, ec);

    // 1 / 2 轮（`kCycles`）：终点都是"回到 TITLE 之后"⇒ 最终工作集应当相同。
    std::vector<ArenaStats> stats(static_cast<std::size_t>(kCycles) + 1);
    std::vector<long> clicks(static_cast<std::size_t>(kCycles) + 1, 0);
    for (int cycles = 1; cycles <= kCycles; ++cycles) {
        const fs::path script = work_dir / ("cycle" + std::to_string(cycles) + ".txt");
        {
            std::ofstream out(script, std::ios::binary | std::ios::trunc);
            out << makeScript(cycles);
        }
        const fs::path log_path = work_dir / ("cycle" + std::to_string(cycles) + ".log");
        std::wstring args;
        args += L"--appdata " + quoteArg(appdata.wstring());
        args += L" --game-dir " + quoteArg(game_dir.wstring());
        args += L" --present window --present-hidden --raster gpu";
        args += L" --native-overrides all --skip-logo";
        args += L" --input-script " + quoteArg(script.wstring());
        args += L" --max-frames 700";
        // ★ 单令牌契约（guest_token.h）：这条子进程跑的是**多线程**路径（音频 feeder 真线程），
        //   必须证明"没有任何一次共享容器访问 / guest 执行发生在令牌之外"。
        args += L" --assert-guest-token";
        const ChildResult r = runChild(exe, args, log_path);
        if (!r.started) LIFT_SKIP("起不了 emulator-lift 子进程（exe 路径不对？）");
        const std::string log = readAllBytes(log_path);
        if (log.empty()) LIFT_SKIP("子进程没写日志（工作目录 / 权限问题）");
        std::printf("option-roundtrip: cycles=%d exit=%lu log=%s (%zu 字节)\n", cycles,
                    static_cast<unsigned long>(r.exit_code), log_path.string().c_str(), log.size());
        if (r.exit_code != 0 && environmentUnavailable(log)) {
            LIFT_SKIP("GPU / 窗口 / 游戏安装不可用 ⇒ 这条不是判据红");
        }
        LIFT_CHECK_EQ_U32(static_cast<std::uint32_t>(r.exit_code), 0u);
        // ② 跑到脚本最后一条 quit（= 第 2 次进 OPTION 之后仍然活着）
        LIFT_CHECK(contains(log, "detail    : input script: quit"));
        // ⑥ 单令牌不变式（summary 的 token 行；子是带 --assert-guest-token 跑的）
        LIFT_CHECK(contains(log, "token     : violations=0"));
        // ③ 分配失败 / 误诊都不许出现
        LIFT_CHECK(!contains(log, "guest 堆耗尽"));
        LIFT_CHECK(!contains(log, "=== unimplemented D3DX9 call ==="));
        LIFT_CHECK(!contains(log, "=== D3DX 资源耗尽"));
        LIFT_CHECK(!contains(log, "unimplemented import"));
        // ④ arena 摘要必须能解析
        stats[cycles] = parseArena(log);
        LIFT_CHECK(stats[cycles].found);
        // ⑤ 应用过的 click = 2 × 轮数
        clicks[cycles] = countAppliedClicks(log);
        LIFT_CHECK_EQ_U32(static_cast<std::uint32_t>(clicks[cycles]),
                          static_cast<std::uint32_t>(2 * cycles));
        std::printf("option-roundtrip: cycles=%d arena surfaces=%llu in_use=%llu peak=%llu largest-free=%llu "
                    "clicks=%ld\n",
                    cycles, stats[cycles].surfaces, stats[cycles].in_use, stats[cycles].peak,
                    stats[cycles].largest_free, clicks[cycles]);
        if (g_failures > 0) break;  // 后续轮数没有再跑的意义（日志也不该被当真）
    }

    if (g_failures == 0 && stats[1].found && stats[2].found) {
        // ★ 容差 1 MiB：见文件头（实测 1/2 轮完全相等；修前泄漏 18,077,080 B/轮）。
        // ★ 2 轮下"不随轮数增长"仍成立：比较段数从 1→2→3 变成 1→2（崩溃在第 2 次进 OPTION）。
        constexpr unsigned long long kArenaTolerance = 1024ull * 1024ull;
        LIFT_CHECK(stats[2].in_use <= stats[1].in_use + kArenaTolerance);
        LIFT_CHECK(stats[2].peak <= stats[1].peak + kArenaTolerance);
        // 泄漏一轮 = 多 3 张纹理（实测 21→24）⇒ +1 的余量足以区分"抖动"与"泄漏"。
        LIFT_CHECK(stats[2].surfaces <= stats[1].surfaces + 1ull);
    }
    return finish("option-roundtrip");
#endif
}
