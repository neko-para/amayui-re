int main(int argc, char** argv) {
    using namespace lift_test;
    // ★ 用例名**保留** `/3cycles`：需求单 `01M6WTRF0X6362NK8BNK8DHHWJ` 与
    //   `01M6X4M4NSRSNX2B0G0DQSFAD1` 的 `repro` 锚点指向它；改名会让
    //   `pnpm tools requirements validate` #3 红，而那两张单不在本次写权限内。
    //   实际轮数 = `kCycles`（= 2）；判据与变异都不依赖这个字符串。
    g_current_case = "option-roundtrip/3cycles";
    // ★ 宿主侧只有"起子进程 / 等它退出 / 读同一份日志"三件事 —— Windows 与 POSIX 都跑。
    const std::vector<std::string> args = lift::argvUtf8(argc, argv);
    if (args.size() < 4) {
        std::fprintf(stderr, "用法：lift-option-roundtrip <emulator-lift> <game-dir> <work-dir>\n");
        return 2;
    }
    const fs::path exe = pathFromUtf8Arg(args[1]);
    const fs::path game_dir = pathFromUtf8Arg(args[2]);
    const fs::path work_dir = pathFromUtf8Arg(args[3]);
    std::error_code ec;
    fs::create_directories(work_dir, ec);
    const fs::path appdata = work_dir / "appdata";
    fs::create_directories(appdata, ec);

    // 1 / 2 轮（`kCycles`）：终点都是"回到 TITLE 之后"⇒ 最终工作集应当相同。
    std::vector<ArenaStats> stats(static_cast<std::size_t>(kCycles) + 1);
    std::vector<long> clicks(static_cast<std::size_t>(kCycles) + 1, 0);
    for (int cycles = 1; cycles <= kCycles; ++cycles) {
        const fs::path script = work_dir / ("cycle" + std::to_string(cycles) + ".txt");
        {
            std::ofstream out(script, std::ios::binary | std::ios::trunc);
            out << makeScript(cycles);
        }
        const fs::path log_path = work_dir / ("cycle" + std::to_string(cycles) + ".log");
        const std::vector<std::string> child_args = makeChildArgs(appdata, game_dir, script);
        const ChildResult r = runChild(exe, child_args, log_path);
        if (!r.started) {
#if !defined(_WIN32)
            std::fprintf(stderr, "option-roundtrip: posix_spawn 失败 errno=%d (%s)\n", r.spawn_error,
                         std::strerror(r.spawn_error));
#endif
            LIFT_SKIP("起不了 emulator-lift 子进程（exe 路径不对 / 沙箱拒绝 spawn？）");
        }
        const std::string log = readAllBytes(log_path);
        if (log.empty()) LIFT_SKIP("子进程没写日志（工作目录 / 权限问题）");
        std::printf("option-roundtrip: cycles=%d exit=%lu%s log=%s (%zu 字节)\n", cycles,
                    static_cast<unsigned long>(r.exit_code), exitNote(r).c_str(),
                    log_path.string().c_str(), log.size());
        if (r.exit_code != 0 && environmentUnavailable(log)) {
            LIFT_SKIP("GPU / 窗口 / 游戏安装不可用 ⇒ 这条不是判据红");
        }
        LIFT_CHECK_EQ_U32(static_cast<std::uint32_t>(r.exit_code), 0u);
        // ② 跑到脚本最后一条 quit（= 第 2 次进 OPTION 之后仍然活着）
        LIFT_CHECK(contains(log, "detail    : input script: quit"));
        // ⑥ 单令牌不变式（summary 的 token 行；子是带 --assert-guest-token 跑的）
        LIFT_CHECK(contains(log, "token     : violations=0"));
        // ③ 分配失败 / 误诊都不许出现
        LIFT_CHECK(!contains(log, "guest 堆耗尽"));
        LIFT_CHECK(!contains(log, "=== unimplemented D3DX9 call ==="));
        LIFT_CHECK(!contains(log, "=== D3DX 资源耗尽"));
        LIFT_CHECK(!contains(log, "unimplemented import"));
        // ④ arena 摘要必须能解析
        stats[cycles] = parseArena(log);
        LIFT_CHECK(stats[cycles].found);
        // ⑤ 应用过的 click = 2 × 轮数
        clicks[cycles] = countAppliedClicks(log);
        LIFT_CHECK_EQ_U32(static_cast<std::uint32_t>(clicks[cycles]),
                          static_cast<std::uint32_t>(2 * cycles));
        std::printf("option-roundtrip: cycles=%d arena surfaces=%llu in_use=%llu peak=%llu largest-free=%llu "
                    "clicks=%ld\n",
                    cycles, stats[cycles].surfaces, stats[cycles].in_use, stats[cycles].peak,
                    stats[cycles].largest_free, clicks[cycles]);
        if (g_failures > 0) break;  // 后续轮数没有再跑的意义（日志也不该被当真）
    }

    if (g_failures == 0 && stats[1].found && stats[2].found) {
        // ★ 容差 1 MiB：见文件头（实测 1/2 轮完全相等；修前泄漏 18,077,080 B/轮）。
        // ★ 2 轮下"不随轮数增长"仍成立：比较段数从 1→2→3 变成 1→2（崩溃在第 2 次进 OPTION）。
        constexpr unsigned long long kArenaTolerance = 1024ull * 1024ull;
        LIFT_CHECK(stats[2].in_use <= stats[1].in_use + kArenaTolerance);
        LIFT_CHECK(stats[2].peak <= stats[1].peak + kArenaTolerance);
        // 泄漏一轮 = 多 3 张纹理（实测 21→24）⇒ +1 的余量足以区分"抖动"与"泄漏"。
        LIFT_CHECK(stats[2].surfaces <= stats[1].surfaces + 1ull);
    }
    return finish("option-roundtrip");
}
