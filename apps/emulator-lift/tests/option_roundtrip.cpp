// emulator-lift · **assets 档**端到端守卫：TITLE ⇄ OPTION 往返时纹理 arena 不许增长
//
// 红了意味着什么（判据，缺一条都不算）：
//   ① 两个子进程（1 / 2 轮往返，见 `kCycles`）都 exit 0；
//   ② 每个子进程都跑到脚本**最后一条 `quit`**（run summary 的 `detail    : input script: quit`）
//      —— 这是"第 2 次仍能进入 OPTION、且退回 TITLE 之后还活着"的机械判据；
//      ★ 崩溃发生在"第 2 次进 OPTION"⇒ 2 轮就够；"不随轮数增长"那条断言在 2 轮下仍成立
//      （只是比较段数从 1→2→3 变成 1→2）。
//   ③ 日志里**没有** 分配失败 / 误诊的痕迹：`guest 堆耗尽`、
//      `=== unimplemented D3DX9 call ===`、`=== D3DX 资源耗尽`、`unimplemented import`；
//   ④ 每一轮的 `arena     : surfaces N in_use U peak P largest-free F` 都被解析到，且
//      `in_use` / `peak` 随轮数**不增长**（容差见下）、`surfaces` 不增长超过 1；
//   ⑤ 第 k 轮日志里应用过的 `click` 动作数 = 2k（k 次进 OPTION + k 次右键回 TITLE）。
//   ⑥ 子进程带 `--assert-guest-token`：run summary 的 `token     : violations=0`（单令牌不变式；
//      "未持令牌就改 GuestHeap / HandleTable / 执行 guest 代码"⇒ 子进程 exit 4）。★ 这条测试
//      是**多线程**的（`--present window` ⇒ 真实时钟 ⇒ 音频 feeder 真线程），所以它是并发契约的
//      端到端判据，不是可选的诊断。
//
// ★ 容差 = 1 MiB（`kArenaTolerance`）。实测（RelWithDebInfo，`--present window --present-hidden
//   --raster gpu`，本机）1/2 轮的三个数**完全相等**：in_use 109,895,008 / peak 126,672,232 /
//   surfaces 23。给 1 MiB 是防 `--present window` 的 real-time 时钟让某一轮的过渡帧多带一张
//   临时纹理。修前（2026-11-08 实测）一次往返泄漏 **18,077,080 B**（TITLE 108,595,152 →
//   往返后 126,672,232，surfaces 21 → 24）⇒ 比容差大 17 倍，判据不会假绿。
//   ⛔ 不要把容差调大到"能盖住一次往返"——那就等于把判据删了。
//
// ★ 为什么用 `--present window --present-hidden --raster gpu`：`--present headless` 是 CPU
//   光栅化，实测 490 帧要 10 分钟以上（本测试 2 轮共约 37 s）；窗口隐藏仍无焦点、无真实光标。
// ★ GPU / 窗口不可用 ⇒ `LIFT_SKIP`(77)（那是"环境不满足"，不是"判据红"）。
// ★ 子进程输出走**文件重定向**（不走管道：受限沙箱里捕获管道会 EPERM）。
